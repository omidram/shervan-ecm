import { PDFDocument, StandardFonts, rgb } from "pdf-lib";
import { ensureDatabase } from "@/lib/bootstrap";
import { fmtDate, fmtNum } from "@/lib/format";
import { latestByVersion } from "@/lib/life";
import { getEngine } from "@/lib/queries";
import { getPersona } from "@/lib/session";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

function wrap(text: string, size = 90) {
  const words = text.split(/\s+/);
  const lines: string[] = [];
  let line = "";
  for (const word of words) {
    const next = line ? `${line} ${word}` : word;
    if (next.length > size) {
      if (line) lines.push(line);
      line = word;
    } else line = next;
  }
  if (line) lines.push(line);
  return lines;
}

export async function GET(request: Request) {
  await ensureDatabase();
  const persona = await getPersona();
  const engineId = new URL(request.url).searchParams.get("engine") || "";
  const found = await getEngine(engineId, persona);
  if (!found) return new Response("Not found", { status: 404 });
  const { engine, assessment } = found;
  const pdf = await PDFDocument.create();
  const font = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  let page = pdf.addPage([595, 842]);
  let y = 800;
  const draw = (text: string, size = 11, useBold = false) => {
    for (const line of wrap(text, size > 14 ? 48 : 88)) {
      if (y < 48) {
        page = pdf.addPage([595, 842]);
        y = 800;
      }
      page.drawText(line, { x: 40, y, size, font: useBold ? bold : font, color: rgb(0.08, 0.12, 0.16) });
      y -= size + 5;
    }
  };
  draw("SHERVAN ECM", 18, true);
  draw("Engine status report", 14, true);
  draw("Planning support only. Not an airworthiness or dispatch decision. Figures are engineering reference models, not controlled OEM limits.");
  draw(`Serial ${engine.serialNumber}   Model ${engine.model.code}   P/N ${engine.partNumber}`);
  draw(`Status ${engine.status}   Owner ${engine.owner.name}   Operator ${engine.operator?.name ?? "-"}`);
  draw(`Build ${fmtDate(engine.buildDate)}   Configuration ${engine.configuration}`);
  y -= 6;
  draw("Reconstructed life", 13, true);
  draw(`TSN ${fmtNum(assessment.life.tsn, 0)} h    CSN ${fmtNum(assessment.life.csn, 0)}`);
  draw(`TSO ${fmtNum(assessment.life.tso, 0)} h    CSO ${fmtNum(assessment.life.cso, 0)}`);
  draw(`Flight hours ${fmtNum(assessment.life.flightHours, 0)}    Flight cycles ${fmtNum(assessment.life.flightCycles, 0)}`);
  draw(`Last shop release ${assessment.life.lastShop ? fmtDate(assessment.life.lastShop) : "-"}`);
  y -= 6;
  draw("Module health", 13, true);
  for (const mod of assessment.modules) draw(`${mod.code}  ${mod.healthIndex ?? "n/a"}  ${mod.stageNote}`);
  y -= 6;
  draw("Open faults", 13, true);
  const faults = assessment.faults.filter((fault) => fault.reported);
  if (!faults.length) draw("None above the reporting threshold.");
  for (const fault of faults) draw(`${fault.titleEn}  ${fmtNum(fault.probability * 100, 0)}%  ${fault.moduleCode}`);
  y -= 6;
  draw("LLP study limits", 13, true);
  if (!assessment.llp.length) draw("No life-limited part on this passport.");
  for (const llp of assessment.llp) {
    draw(`${llp.serialNumber}  ${llp.partNumber}  remaining ${fmtNum(llp.remaining, 0)} of ${fmtNum(llp.lifeLimitCycles, 0)} (${fmtNum(llp.remainingPct, 1)}%)`);
  }
  y -= 6;
  draw("Ownership", 13, true);
  for (const row of engine.transfers) draw(`${fmtDate(row.transferredAt)}  ${row.toOrg.name}`);
  y -= 6;
  draw("Latest maintenance", 13, true);
  for (const record of latestByVersion(engine.records).slice(0, 8)) {
    draw(`${fmtDate(record.performedAt)}  ${record.type}  ${record.titleEn}  ${record.approvalStatus}`);
  }
  draw("Generated by SHERVAN ECM. Original product diagrams are not included in this text report.");
  const bytes = await pdf.save();
  return new Response(Buffer.from(bytes), {
    headers: {
      "Content-Type": "application/pdf",
      "Content-Disposition": `attachment; filename="shervan-status-${engine.serialNumber}.pdf"`,
      "Cache-Control": "no-store",
    },
  });
}
